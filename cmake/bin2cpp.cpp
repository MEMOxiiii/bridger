// Build-time helper for cmake/EmbedResource.cmake: writes a .cpp defining
//   namespace bridger::embedded { extern const unsigned char <symbol>[]; extern const std::size_t <symbol>_size; }
// Usage: bridger_bin2cpp <input> <output.cpp> <symbol>

#include <cstdio>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

int main(int argc, char** argv) {
    if (argc != 4) {
        std::fprintf(stderr, "usage: bridger_bin2cpp <input> <output.cpp> <symbol>\n");
        return 2;
    }
    std::ifstream in(argv[1], std::ios::binary);
    if (!in) {
        std::fprintf(stderr, "bin2cpp: cannot read %s\n", argv[1]);
        return 1;
    }
    const std::vector<unsigned char> data{std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>()};
    const std::string sym = argv[3];

    std::string out;
    out.reserve(data.size() * 5 + 512);
    out += "// Generated by cmake/bin2cpp.cpp - do not edit.\n#include <cstddef>\nnamespace bridger::embedded {\n";
    out += "extern const unsigned char " + sym + "[];\nextern const std::size_t " + sym + "_size;\n";
    out += "alignas(16) const unsigned char " + sym + "[] = {\n";
    static const char* hex = "0123456789abcdef";
    for (std::size_t i = 0; i < data.size(); ++i) {
        out += "0x";
        out += hex[data[i] >> 4];
        out += hex[data[i] & 15];
        out += (i % 24 == 23) ? ",\n" : ",";
    }
    if (data.empty()) out += "0";
    out += "\n};\nconst std::size_t " + sym + "_size = " + std::to_string(data.size()) + ";\n}\n";

    std::ofstream f(argv[2], std::ios::binary);
    f.write(out.data(), static_cast<std::streamsize>(out.size()));
    return f ? 0 : 1;
}
