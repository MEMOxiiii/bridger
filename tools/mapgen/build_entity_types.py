#!/usr/bin/env python3
"""Builds src/translate/entity_types.inc: every vanilla entity type with its Java and Bedrock identifiers and the game
version each name was introduced in (docs/formats/bedrock-world.md, "Mobs").

Source: HiveGamesOSS/Chunker (MIT), pinned commit below: JavaEntityTypeResolver and BedrockEntityTypeResolver map one
enum per entity type to an identifier, inside `if (version.isGreaterThanOrEqual(a, b, c))` blocks; a later block that
maps the same enum again renames it. Bedrock versions are written as Chunker writes them (26.50 is 1.26.50).

    python tools/mapgen/build_entity_types.py
"""

import re
import urllib.request
from pathlib import Path

COMMIT = "50aaf6d82e8b68929279161b790d95fdddfe0a40"
BASE = f"https://raw.githubusercontent.com/HiveGamesOSS/Chunker/{COMMIT}/cli/src/main/java/com/hivemc/chunker/conversion/encoding/"
FILES = {"java": "java/base/resolver/entity/JavaEntityTypeResolver.java",
         "bedrock": "bedrock/base/resolver/entity/BedrockEntityTypeResolver.java"}
OUT = Path(__file__).resolve().parents[2] / "src" / "translate" / "entity_types.inc"

PUT = re.compile(r'^\s*mapping\.put\(ChunkerVanillaEntityType\.([A-Z0-9_]+),\s*"([^"]+)"\)')
IF_VERSION = re.compile(r"^(\s*)if \((?:bedrock)?[vV]ersion\.isGreaterThanOrEqual\((\d+),\s*(\d+),\s*(\d+)\)\)\s*\{")


def histories(text):
    """enum -> [(version triple, identifier)] in source order."""
    out, version, indent = {}, (0, 0, 0), None
    for line in text.splitlines():
        m = IF_VERSION.match(line)
        if m:
            indent, version = m.group(1), tuple(int(x) for x in m.groups()[1:])
            continue
        if indent is not None and line.rstrip() == indent + "}":
            indent, version = None, (0, 0, 0)
            continue
        m = PUT.match(line)
        if m:
            out.setdefault(m.group(1), []).append((version, m.group(2)))
    return out


def cpp_list(name, hist):
    if not hist:
        return f"inline constexpr std::array<IdSince, 0> {name}{{}};"
    items = ", ".join(f'{{{{{v[0]}, {v[1]}, {v[2]}}}, "{ident}"}}' for v, ident in hist)
    return f"inline constexpr std::array<IdSince, {len(hist)}> {name}{{{{{items}}}}};"


def main():
    src = {side: urllib.request.urlopen(BASE + path, timeout=60).read().decode("utf-8") for side, path in FILES.items()}
    java, bedrock = histories(src["java"]), histories(src["bedrock"])
    names = sorted(set(java) | set(bedrock))
    lines = [
        "// Generated by tools/mapgen/build_entity_types.py from HiveGamesOSS/Chunker@" + COMMIT,
        "// (JavaEntityTypeResolver, BedrockEntityTypeResolver; MIT). Do not edit by hand.",
        "// For each entity type: its Java and Bedrock identifiers with the version each was introduced in (a later entry",
        "// renames the type from that version on). Bedrock versions as Chunker writes them: 26.50 is {1, 26, 50}.",
        "",
    ]
    for n in names:
        lines.append(cpp_list(f"kJava_{n}", java.get(n, [])))
        lines.append(cpp_list(f"kBedrock_{n}", bedrock.get(n, [])))
    lines.append("")
    lines.append(f"inline constexpr std::array<EntityTypeRow, {len(names)}> kEntityTypes{{{{")
    for n in names:
        lines.append(f'    {{"{n.lower()}", kJava_{n}, kBedrock_{n}}},')
    lines.append("}};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    both = sum(1 for n in names if n in java and n in bedrock)
    print(f"wrote {OUT}: {len(names)} types ({both} in both editions, {len(java)} Java, {len(bedrock)} Bedrock)")


if __name__ == "__main__":
    main()
